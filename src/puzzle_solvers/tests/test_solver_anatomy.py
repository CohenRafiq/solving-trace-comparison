def test_a_zero_init_gradient_descent_ensemble_is_a_no_op():
    """Why gradient descent is ensembled by init, never by schedule alone.

    A zero-init gradient-descent row draws nothing from `Problem.rng`: its `k`
    members are `k` copies of one trace and `Mean(k)` averages them back into
    that trace. `gd_adam_random_init_population` is registered precisely because
    it perturbs the starting point, which *is* the row's only entropy.
    """
    zero_init_ensembles = [
        n
        for n in SOLVERS
        if SOLVERS[n].proposal.kind == "gradient_descent"
        and SOLVERS[n].aggregation.k > 1
        and SOLVERS[n].proposal.init == "zeros"
    ]
    assert not zero_init_ensembles, (
        f"{zero_init_ensembles} average identical trajectories"
    )
    # The one registered gradient-descent ensemble is a real one.
    row = SOLVERS["gd_adam_random_init_population"]
    assert row.proposal.init == "random" and row.aggregation.k > 1


