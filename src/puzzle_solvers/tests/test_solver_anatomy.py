def reference_steps(solver: BaseSolver, n: int) -> list[np.ndarray]:
    """`n` recorded steps of `solver`, driven directly rather than through `solve`.

    `solve` returns whatever fitted in the time budget, so its length is a
    property of the machine as much as of the solver. This walks the same
    `reset`/`advance` pair with `deadline=None`, making the result a function of
    the anatomy alone.
    """
    problem = make_problem()
    state = solver.reset(problem)
    steps = []
    for _ in range(n):
        state = solver.advance(state, problem)
        steps.append(state.grid.copy())
    return steps


def make_problem(clues=CLUES, grid=GRID, seed=0):
    return Problem(
        clues=clues,
        shape=tuple(int(d) for d in grid.shape),
        rng=np.random.default_rng(seed),
        seed=seed,
    )


