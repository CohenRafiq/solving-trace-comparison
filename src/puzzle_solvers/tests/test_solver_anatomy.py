def test_an_ensemble_row_changes_exactly_one_axis():
    """An ensemble must not quietly change its schedule as well as its size.

    A `Mean(k)` row over a deterministic (proposal, schedule) pair is a no-op:
    `k` copies of the same trace average to that trace. The tempting fix is to
    swap in a stochastic schedule, but that is a second axis, and for gradient
    descent it is a costly one -- its gradient is taken over the whole grid, so
    `Local` (one random cell per step) took `gd_adam` from 3/10 solved to 0/10
    while the ensemble on top bought nothing. This test is what stops the next
    such row from being added.
    """
    for ensemble, scalar in ENSEMBLE_SIBLINGS:
        row, sibling = ALL_ANATOMIES[ensemble], ALL_ANATOMIES[scalar]
        assert row.schedule == sibling.schedule, (
            f"{ensemble} uses {row.schedule.kind} but {scalar} uses "
            f"{sibling.schedule.kind}: that is two axes, not one"
        )
        for axis in ("proposal", "schedule", "coupling"):
            assert row.describe()[axis] == sibling.describe()[axis], axis


def test_registered_ensembles_are_all_one_axis_from_their_sibling():
    """Every uncoupled `Mean(k)` row must have a scalar sibling, and vice versa.

    `SOLVERS` is a catalogue, so a new row can be added without anyone noticing
    it is a no-op. Two things have to hold, and neither is automatic:

    * every uncoupled `Mean(k)` row names a scalar sibling it differs from in
      `aggregation` alone (checked per-pair in
      `test_an_ensemble_row_changes_exactly_one_axis`);
    * no ensemble row is orphaned -- it has a sibling registered too, so the pair
      is actually comparable in the dataset.

    Coupled rows are excluded deliberately. `genetic_tournament` and
    `genetic_proportionate` are both `Mean(k)`, but the coupling is where their
    entropy comes from; there is no `Identity` row for either to be a sibling of,
    and asking for one would force a second genetic architecture into the
    catalogue purely to satisfy the rule.
    """
    ensembles = {
        n for n in SOLVERS if SOLVERS[n].aggregation.k > 1 and type(SOLVERS[n].coupling) is Coupling
    }
    for ensemble, scalar in ENSEMBLE_SIBLINGS:
        if ensemble in SOLVERS:
            assert scalar in SOLVERS, f"{ensemble} ships without its sibling {scalar}"
    registered_pairs = {e for e, _ in ENSEMBLE_SIBLINGS} & ensembles
    assert registered_pairs == ensembles, (
        f"uncatalogued ensemble row(s): {sorted(ensembles - registered_pairs)}"
    )


