def make_puzzle(seed=3, density=0.45, k=3):
    """A random puzzle as `(clues, grid)`, with `clues` shaped `(2, 5, k)`."""
    rng = np.random.default_rng(seed)
    grid = (rng.random((5, 5)) < density).astype(np.float32)
    rows, cols = derive_clues_from_grid(grid.astype(np.int8), k)
    pad = np.zeros((2, 5, k), dtype=np.float32)
    for axis, clue_rows in enumerate((rows, cols)):
        for i, clue in enumerate(clue_rows):
            for j, v in enumerate(clue):
                if v > 0:
                    pad[axis, i, j] = v
    return pad, grid


