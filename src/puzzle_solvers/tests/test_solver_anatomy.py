def test_zero_init_is_the_default_and_changes_nothing():
    """`init="zeros"` must be a no-op, so existing traces stay comparable.

    Adding the `init` knob is only safe if the default reproduces the pre-knob
    `GradientDescent` exactly. The starting logits are `zeros` either way, and
    `initial` never touches `Problem.rng` on this path, so the trajectory has to
    be the old one step for step -- a stray draw would show up in step 1, not
    just in the starting grid.

    Driven through `reset`/`advance` rather than `solve` on purpose: the
    trajectory is a property of the anatomy, the step count is a property of the
    machine. See `GD_ADAM_PREFIX`.
    """
    assert GradientDescent().init == "zeros"
    solver = BaseSolver(SOLVERS["gd_adam"])
    assert np.allclose(solver.reset(make_problem()).grid, 0.5)

    steps = reference_steps(solver, len(GD_ADAM_PREFIX))
    for got, want in zip(steps, GD_ADAM_PREFIX, strict=True):
        assert np.allclose(got, want, atol=1e-6)


def test_zeros_init_ignores_init_scale():
    """`init_scale` only parameterises the random draw, so it is inert here.

    Worth its own test because the knob and the path that ignores it are the same
    code: if someone routes the zeros start through the same sampler, this is
    what catches it.
    """

    def zeros_start(scale):
        solver = BaseSolver(
            Anatomy(
                "probe",
                GradientDescent(rule=Adam(step_size=1.5), init="zeros", init_scale=scale),
                Global(),
                Identity(),
            )
        )
        return solver.reset(make_problem()).grid

    reference = zeros_start(0.25)
    for scale in (0.0, 0.25, 10.0):
        assert np.array_equal(zeros_start(scale), reference), (
            f"init_scale={scale} moved the zeros start"
        )


def test_the_untruncated_zeros_trace_stops_on_a_revisit_at_the_tightened_eps():
    """Where `gd_adam` ends without a clock in the way.

    Pinned rather than incidental because the value moved: `stopping_eps` was
    tightened from 5e-3 to 1e-3 in the refactor, which pushed the first revisit
    from index 154 to 186 on an identical trajectory. A future change to that
    tolerance should show up as a diff on one number here instead of as a
    thousand silently truncated traces.
    """
