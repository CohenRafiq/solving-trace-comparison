# -- ensembles -----------------------------------------------------------


def _distinct_members(name, steps=3, seed=0, k=None):
    """How many distinct member grids a row has after `steps`."""
    anatomy = ALL_ANATOMIES[name]
    if k is not None:
        anatomy = replace(anatomy, aggregation=Mean(k=k))
    solver = BaseSolver(anatomy)
    problem = make_problem(seed=seed)
    state = solver.reset(problem)
    for _ in range(steps):
        state = solver.advance(state, problem)
    return len({m.grid.tobytes() for m in member_states(state)})


@pytest.mark.parametrize("name", sorted(n for n in SOLVERS if SOLVERS[n].aggregation.k > 1))
def test_every_registered_ensemble_is_actually_an_ensemble(name):
    """Guard against a `Mean(k)` row that silently reduces to a single run.

    Averaging `k` trajectories only means something if the trajectories differ.
    A (proposal, schedule) pair that never draws from `Problem.rng` produces `k`
    identical traces, so the row looks like an ensemble in `describe()` and in
    the trace metadata while carrying exactly the information of one solver.
    This is why `model_solver` has no population row: its forward pass runs
    under `model.eval()`, so it is deterministic under every schedule.
    """
    distinct = _distinct_members(name)
    assert distinct > 1, (
        f"{name} has k={SOLVERS[name].aggregation.k} but all members are identical, "
        "so Mean(k) is a no-op wrapper -- give it a stochastic schedule first"
    )


def test_mean_of_a_deterministic_proposal_is_still_one_trajectory():
    """The degenerate case the guard above exists to catch, pinned as fact.

    `mac` has a deterministic global sweep, so 8 of them are 8 copies of the
    same trace. This is arithmetic, not a bug: no amount of seeding will make a
    deterministic policy produce variety.
    """
    assert _distinct_members("mac", k=8) == 1
    assert _distinct_members("mac_random_line", k=8) > 1


def test_ensemble_members_keep_independent_random_streams():
    """Each member owns a stream, so its trajectory ignores the others.

    Stepping the same members in reverse order must give the same answer per
    member. Before the per-member streams existed all members shared one
    generator, so member 0's draws landed first and every later member inherited
    wherever the previous one stopped -- order was part of the algorithm.
    """
    solver = build_solver("mac_population")
    k = solver.anatomy.aggregation.k

    def batched():
        problem = make_problem(seed=0)
        state = solver.reset(problem)
        for _ in range(3):
            state = solver.advance(state, problem)
        return state.members

    def interleaved():
        problem = make_problem(seed=0)
        members = solver.reset(problem).members
        problems = member_problems(problem, k)
        for _ in range(3):
            for i in reversed(range(k)):
                members[i] = solver.anatomy.schedule.apply(
                    solver.anatomy.proposal, members[i], problems[i]
                )
        return members

    forward, reverse = batched(), interleaved()
    assert all(a.grid.tobytes() == b.grid.tobytes() for a, b in zip(forward, reverse, strict=True))


