@pytest.mark.parametrize("name", GD_ROWS)
def test_gradient_descent_runs_under_every_schedule(name):
    """Gradient descent must accept whatever subset the schedule hands it.

    The gradient is taken over the whole grid, so the update rule has to narrow
    it to the selected cells before writing moments and deltas. It used to mix
    the two widths, which made every non-`global` combination unusable:
    `Parallel` mixed a subset `idxs` with a full-width `grad`, and `Sequential`
    always selects a single cell.
    """
    solver = build_solver(name)
    problem = make_problem(seed=1)
    state = solver.reset(problem)
    for _ in range(3):
        state = solver.advance(state, problem)
    assert state.grid.shape == (5, 5)


@pytest.mark.parametrize("rule", [Adam(step_size=1.5), SGD(step_size=70.0), BangBang()])
def test_full_width_updates_are_bit_identical_to_the_pre_fix_formula(rule):
    """The subset fix must not disturb the rows that always select every cell.

    A `Global` schedule keeps `idxs` full width, so `grad[idxs] == grad` and
    the arithmetic has to come out exactly as it did before the fix -- otherwise
    every existing `gd_*` trace in `data/traces_dataset` stops reproducing.
    """
    torch.manual_seed(0)
    n = 25
    idxs = torch.arange(n)
    grad = torch.randn(n)
    moments = (torch.randn(n), torch.rand(n), torch.zeros(n, dtype=torch.long))
    fresh = tuple(t.clone() for t in moments)

    old_moments, old_delta = _pre_fix_update(rule, moments, grad, idxs)
    new_moments, new_delta = rule.update(fresh, grad, idxs)

    assert torch.equal(new_delta, old_delta)
    for a, b in zip(new_moments, old_moments, strict=True):
        assert torch.equal(a, b)


def _pre_fix_update(rule, moments, grad, idxs):
    """The pre-fix formulas, which mixed full-width `grad` with subset `idxs`."""
    if isinstance(rule, Adam):
        m_all, v_all, t_all = (t.clone() for t in moments)
        t_all[idxs] = t_all[idxs] + 1
        t = t_all[idxs].float()
        m = rule.beta1 * m_all[idxs] + (1 - rule.beta1) * grad
        v = rule.beta2 * v_all[idxs] + (1 - rule.beta2) * grad.pow(2)
        m_all[idxs] = m
        v_all[idxs] = v
        m_hat = m / (1 - rule.beta1**t)
        v_hat = v / (1 - rule.beta2**t)
        return (m_all, v_all, t_all), rule.step_size * m_hat / (v_hat.sqrt() + rule.eps)
    if isinstance(rule, SGD):
        return moments, rule.step_size * grad
    return moments, rule.step_size * torch.sign(grad) * torch.sqrt(torch.abs(grad) + 1e-8)


