def test_the_same_seed_reproduces_the_same_trace():
    """Same seed, same trace -- but only if the time budget did not bind.

    `max_time` is wall-clock, so a run that gets cut off mid-search would
    otherwise look like a reproducibility failure. Warm up first (the first
    torch call in a process is slow), then require the solver to stop on its own
    and compare the full traces.
    """
    clues, grid = make_puzzle(seed=2)
    for name in ("mac", "backtracking_search", "genetic_tournament", "gd_adam"):
        solver = build_solver(name)
        solver.solve(clues, grid, max_time=1.0, seed=1)  # warm up torch/autograd
        a = solver.solve(clues, grid, max_time=120.0, seed=5)
        b = solver.solve(clues, grid, max_time=120.0, seed=5)
        assert a[2] is not StoppingReason.TIMEOUT, f"{name} hit the time budget"
        assert a[1] == b[1], name
        assert np.array_equal(a[0], b[0]), name


